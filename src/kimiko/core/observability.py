"""Observability — Prometheus metrics for Kimiko (Fix #7).

Exposes counters, histograms, and gauges for request latency,
LLM generation, memory retrieval, and active sessions.
"""

from __future__ import annotations

from prometheus_client import Counter, Gauge, Histogram, Info

# ── App Info ──
APP_INFO = Info("kimiko", "Kimiko AI platform info")

# ── HTTP ──
HTTP_REQUEST_DURATION = Histogram(
    "kimiko_http_request_duration_seconds",
    "HTTP request latency",
    labelnames=["method", "endpoint", "status_code"],
    buckets=[0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0, 30.0],
)

HTTP_REQUESTS_TOTAL = Counter(
    "kimiko_http_requests_total",
    "Total HTTP requests",
    labelnames=["method", "endpoint", "status_code"],
)

# ── LLM ──
LLM_GENERATION_DURATION = Histogram(
    "kimiko_llm_generation_duration_seconds",
    "LLM generation latency",
    labelnames=["model"],
    buckets=[0.5, 1.0, 2.5, 5.0, 10.0, 30.0, 60.0, 120.0],
)

LLM_TOKENS_GENERATED = Counter(
    "kimiko_llm_tokens_generated_total",
    "Total tokens generated by LLM",
    labelnames=["model"],
)

LLM_ERRORS = Counter(
    "kimiko_llm_errors_total",
    "Total LLM errors",
    labelnames=["model", "error_type"],
)

# ── Memory & Retrieval ──
MEMORY_RETRIEVAL_DURATION = Histogram(
    "kimiko_memory_retrieval_duration_seconds",
    "Memory retrieval latency",
    labelnames=["memory_type"],
    buckets=[0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0],
)

VECTOR_SEARCH_DURATION = Histogram(
    "kimiko_vector_search_duration_seconds",
    "Vector search latency",
    buckets=[0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5],
)

# ── Sessions ──
ACTIVE_SESSIONS = Gauge(
    "kimiko_active_sessions",
    "Number of active chat sessions",
)

# ── Streaming ──
STREAM_CONNECTIONS = Gauge(
    "kimiko_stream_connections_active",
    "Active streaming connections",
)


def init_metrics() -> None:
    """Initialize app-level metrics info."""
    from kimiko import __version__

    APP_INFO.info({"version": __version__, "name": "kimiko"})
